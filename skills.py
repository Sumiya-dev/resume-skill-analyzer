def get_skill_categories() -> Dict[str, List[str]]:
    """Return the dictionary of skill categories."""
    return SKILL_CATEGORIES


def get_all_skills() -> Set[str]:
    """Return a flat set of all canonical skill names across categories."""
    all_skills = set()
    for skills in SKILL_CATEGORIES.values():
        all_skills.update(skills)
    return all_skills


def get_category_for_skill(skill_name: str) -> str:
    """Return the category name for a given canonical skill name."""
    skill_lower = skill_name.strip().lower()
    if skill_lower in SKILL_ALIASES:
        return SKILL_ALIASES[skill_lower][1]
    for category, skills in SKILL_CATEGORIES.items():
        for s in skills:
            if s.lower() == skill_lower:
                return category
    return "Other"
